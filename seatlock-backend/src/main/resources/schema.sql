-- ============================================================================
-- SeatLock — Database Schema
-- ============================================================================
-- This script runs on every startup (spring.sql.init.mode=always).
-- Use IF NOT EXISTS / CREATE OR REPLACE to make it idempotent.
-- ============================================================================

-- 1. Seats ──────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS seats (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seat_number VARCHAR(10)  NOT NULL UNIQUE,
    status      VARCHAR(20)  NOT NULL DEFAULT 'AVAILABLE',
    version     BIGINT       NOT NULL DEFAULT 0,
    updated_at  TIMESTAMP WITH TIME ZONE
);

-- 2. Seat Locks (temporary 2-minute reservations) ───────────────────────────

CREATE TABLE IF NOT EXISTS seat_locks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seat_id     BIGINT       NOT NULL,
    session_id  VARCHAR(36)  NOT NULL,
    locked_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT fk_seat_locks_seat FOREIGN KEY (seat_id) REFERENCES seats(id)
);

CREATE INDEX IF NOT EXISTS idx_seat_locks_session  ON seat_locks(session_id);
CREATE INDEX IF NOT EXISTS idx_seat_locks_status   ON seat_locks(status);
CREATE INDEX IF NOT EXISTS idx_seat_locks_expiry   ON seat_locks(expires_at);

-- 3. Bookings (confirmed reservations) ──────────────────────────────────────

CREATE TABLE IF NOT EXISTS bookings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seat_id         BIGINT       NOT NULL UNIQUE,  -- prevents double-booking
    session_id      VARCHAR(36)  NOT NULL,
    passenger_name  VARCHAR(255) NOT NULL,
    booked_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_bookings_seat FOREIGN KEY (seat_id) REFERENCES seats(id)
);
